#!/usr/bin/env python3
"""Generate resources/settings.xml (Kodi settings format version 1).

The five location categories are identical apart from the slot number, so
they are generated rather than maintained by hand. Run after changing:

    python3 tools/gen_settings.py
"""
import os
import sys
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'resources', 'lib'))

from smhi import ADDON_ID  # noqa: E402
from smhi.config import (FC_CUSTOM, FC_OTHER_STATION, FC_STATION, SLOTS,  # noqa: E402
                         STATION_FIELDS, STATION_ROLES, STATIONS_SUMMARY)

# strings.po ids of the observation station settings
S_STATIONS = 32022
S_EDIT_STATIONS = 32023
S_HELP_STATIONS = 32061

def string(sid, label, help_='', visible_if=None, read_only=False, hidden=False, heading=None):
    deps = []
    extra = '<visible>false</visible>' if hidden else ''
    if read_only:
        # enabled only when the value equals a sentinel it never has: the
        # station name is shown but can only be changed with the pick button
        deps.append(f'<dependency type="enable"><condition operator="is" '
                    f'setting="{sid}">__never__</condition></dependency>')
    if visible_if:
        deps.append(_visible(*visible_if))
    dep_xml = f'<dependencies>{"".join(deps)}</dependencies>' if deps else ''
    return f'''
        <setting id="{sid}" type="string" label="{label}" help="{help_}">
          <level>0</level>
          <default/>
          <constraints><allowempty>true</allowempty></constraints>
          {extra}{dep_xml}
          <control type="edit" format="string"><heading>{heading or label}</heading></control>
        </setting>'''


def _visible(setting, value):
    return (f'<dependency type="visible"><condition operator="is" setting="{setting}">'
            f'{value}</condition></dependency>')


def action(sid, label, data, help_='', visible_if=None):
    deps = f'<dependencies>{_visible(*visible_if)}</dependencies>' if visible_if else ''
    return f'''
        <setting id="{sid}" type="action" label="{label}" help="{help_}">
          <level>0</level>
          <data>{escape(data)}</data>
          <constraints><allowempty>true</allowempty></constraints>
          {deps}
          <control type="button" format="action"><close>true</close></control>
        </setting>'''


def hidden(sid):
    return string(sid, 32020, hidden=True)


def station_rows(n):
    """Settings XML for the observation stations of location ``n``."""
    # The stations are edited in a list dialog (settings_ui.edit_stations), so
    # the settings page only shows a read-only summary and the button that
    # opens the editor. The rows themselves are hidden settings, which the
    # editor reads and writes.
    k = lambda name: f'loc{n}_{name}'
    hidden_rows = ''.join(hidden(k(f'{role}_{f}')) for role in STATION_ROLES for f in STATION_FIELDS)
    return f'''
        {string(k(STATIONS_SUMMARY), S_STATIONS, S_HELP_STATIONS, read_only=True)}
        {action(k('edit_stations'), S_EDIT_STATIONS, f'RunScript({ADDON_ID},stations,{n})', S_HELP_STATIONS)}{hidden_rows}'''


def slot(n):
    """Settings XML for the category (tab) of location ``n``."""
    k = lambda name: f'loc{n}_{name}'
    run = lambda verb, role: f'RunScript({ADDON_ID},{verb},{n},{role})'
    other = (k('fc_source'), FC_OTHER_STATION)
    custom = (k('fc_source'), FC_CUSTOM)
    return f'''
    <category id="loc{n}" label="{32010 + n}" help="">
      <group id="1" label="32021">
        {string(k('name'), 32020, 32060)}{station_rows(n)}
      </group>
      <group id="2" label="32030">
        <setting id="{k('fc_source')}" type="integer" label="32031" help="32063">
          <level>0</level>
          <default>{FC_STATION}</default>
          <constraints>
            <options>
              <option label="32032">{FC_STATION}</option>
              <option label="32033">{FC_OTHER_STATION}</option>
              <option label="32034">{FC_CUSTOM}</option>
            </options>
          </constraints>
          <control type="spinner" format="string"/>
        </setting>
        {string(k('fc_name'), 32035, read_only=True, visible_if=other)}
        {action(k('pick_forecast'), 32036, run('pick', 'forecast'), visible_if=other)}
        {string(k('lat'), 32037, 32064, visible_if=custom)}
        {string(k('lon'), 32038, 32064, visible_if=custom)}
        {hidden(k('fc_id'))}
        {hidden(k('fc_lat'))}
        {hidden(k('fc_lon'))}
      </group>
    </category>'''


def generate() -> str:
    body = ''.join(slot(n) for n in range(1, SLOTS + 1))
    xml = f'''<?xml version="1.0" encoding="utf-8" standalone="yes"?>
<!-- Generated by tools/gen_settings.py - do not edit by hand. -->
<settings version="1">
  <section id="{ADDON_ID}">{body}
  </section>
</settings>
'''
    # drop the blank lines left by empty template slots
    return '\n'.join(line for line in xml.splitlines() if line.strip()) + '\n'


if __name__ == '__main__':
    out = os.path.join(ROOT, 'resources', 'settings.xml')
    with open(out, 'w', encoding='utf-8') as f:
        f.write(generate())
    print(f'wrote {out}')
